/**
 * Translate a key for the given language, with optional parameter
 * substitution. Uses {name} style placeholders.
 */
export function t(
  lang: Lang,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  let str = translations[lang]?.[key] ?? translations.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return str;
}

/**
 * Get the stored language from localStorage, or null if not set yet.
 */
export function getStoredLang(): Lang | null {
  if (typeof window === "undefined") return null;
  const stored = localStorage.getItem("lora-lang");
  if (stored && stored in translations) return stored as Lang;
  return null;
}

/**
 * Save the language choice to localStorage.
 */
export function setStoredLang(lang: Lang): void {
  if (typeof window !== "undefined") {
    localStorage.setItem("lora-lang", lang);
  }
}
